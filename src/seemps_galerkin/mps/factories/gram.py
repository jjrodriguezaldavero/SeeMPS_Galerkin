from __future__ import annotations

import numpy as np
from collections.abc import Sequence

from seemps.state import MPS, Simplification, Strategy, Truncation
from seemps.operators import MPO, MPOSum, simplify_mpo

from ...logger import Logger
from ..defaults import DEFAULT_SVD_STRATEGY
from .utils import mpo_identity, mpo_tensor_product, mps_insert_zero_site
from .multiplication import _mpo_slice_add, _mpo_slice_subtract, mpo_nd_mult

# Compression of the exact Gram construction to (essentially) machine precision.
GRAM_STRATEGY = Strategy(
    method=Truncation.RELATIVE_SINGULAR_VALUE,
    tolerance=1e-15,
    simplification_tolerance=1e-15,
    simplify=Simplification.CANONICAL_FORM,
)


def mps_gram_weights(n: int) -> MPS:
    """QTT of w_k = ∫T_k = 2/(1-k²) for even k and 0 for odd k, 0 ≤ k < 2ⁿ, LSB-first."""
    k = np.arange(2**n)
    w = np.zeros(2**n, dtype=float)
    even = k % 2 == 0
    w[even] = 2.0 / (1.0 - k[even] ** 2)
    # MPS.from_vector places the most significant bit first; reverse the bits of the index.
    reversal = np.zeros_like(k)
    for bit in range(n):
        reversal |= ((k >> bit) & 1) << (n - 1 - bit)
    return MPS.from_vector(w[reversal], [2] * n, strategy=GRAM_STRATEGY, normalize=False)


def mpo_gram(n: int) -> MPO:
    """Chebyshev Gram matrix G_ij = ∫T_i T_j over 0 ≤ i, j < 2ⁿ, as an LSB-first MPO.

    Uses G = ½[H(w) + L(w) + U(w)] - I, with H the Hankel and L, U the lower and upper
    Toeplitz operators generated by the QTT of w. Since i + j < 2ⁿ⁺¹, the operators are
    built on n + 1 sites and the most significant site is then fixed to i = j = 0. The
    construction is exact for the given QTT of w, with bond dimension at most 6χ_w + 1.
    """
    if n < 1:
        raise ValueError
    ψ_w = mps_gram_weights(n + 1)
    cores = ψ_w._data
    terms = [
        MPO(_mpo_slice_add(cores)),
        MPO(_mpo_slice_subtract(cores, is_upper=False)),
        MPO(_mpo_slice_subtract(cores, is_upper=True)),
        mpo_identity(n + 1),
    ]
    data = list(MPOSum(terms, [0.5, 0.5, 0.5, -1.0]).join()._data)

    # Restrict to the leading 2ⁿ × 2ⁿ block by fixing the most significant site.
    last = data.pop()[:, 0, 0, :]
    data[-1] = np.tensordot(data[-1], last, axes=(3, 0))
    mpo = simplify_mpo(MPO(data), strategy=GRAM_STRATEGY)

    Logger.log(
        f"[Gram MPO] n={n}, χ_w={ψ_w.max_bond_dimension()}, "
        f"χ={max(mpo.bond_dimensions(), default=1)}",
        level=2,
    )
    Logger.dump("gram.TT.bond_dimensions", mpo.bond_dimensions())
    return mpo


def mpo_nd_gram(
    sites_per_dimension: Sequence[int], svd_strategy: Strategy = DEFAULT_SVD_STRATEGY
) -> MPO:
    mpos = [simplify_mpo(mpo_gram(n_k), strategy=svd_strategy) for n_k in sites_per_dimension]
    return mpo_tensor_product(mpos)


def mpo_weighted_gram(
    ψ: MPS,
    sites_per_dimension: Sequence[int],
    svd_strategy: Strategy = DEFAULT_SVD_STRATEGY,
    ρ_G_expand: MPO | None = None,
) -> MPO:
    if ψ.size != sum(sites_per_dimension):
        raise ValueError

    # Expand the initial state across dimensions
    ψ_expand = ψ.copy()
    offset = 0
    for n in sites_per_dimension:
        ψ_expand = mps_insert_zero_site(ψ_expand, offset + n)
        offset += n + 1

    # Compute the expanded multiplication MPO
    sites_expand = [n + 1 for n in sites_per_dimension]
    # Remove redundant carry/borrow states before multiplying by the Gram MPO.
    # Affine parameter fields otherwise produce very large temporary bonds.
    ρ_Q_expand = simplify_mpo(mpo_nd_mult(ψ_expand, sites_expand), strategy=svd_strategy)

    # Compute the expanded Gram MPO
    if ρ_G_expand is None:
        ρ_G_expand = mpo_nd_gram(sites_expand, svd_strategy)
    elif ρ_G_expand.size != sum(sites_expand):
        raise ValueError

    # Project out the inserted zero sites before truncating. Truncating the
    # expanded product loses small affine couplings that spatial derivatives
    # subsequently amplify in the stiffness matrix.
    ρ_QG_expand = (ρ_G_expand @ ρ_Q_expand).join()

    # Remove the redundant MPO cores
    data = list(ρ_QG_expand._data)
    positions = np.cumsum(sites_expand) - 1
    for pos in reversed(positions.tolist()):
        core = data.pop(pos)[:, 0, 0, :]
        if pos < len(data):
            data[pos] = np.tensordot(core, data[pos], axes=(1, 0))
        else:
            data[pos - 1] = np.tensordot(data[pos - 1], core, axes=(3, 0))
    return simplify_mpo(MPO(data), strategy=svd_strategy)
